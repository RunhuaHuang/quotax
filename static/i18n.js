export function getLang() {
  try {
    return JSON.parse(localStorage.getItem(PREFS_KEY) || "{}").lang || "zh-CN";
  } catch {
    return "zh-CN";
  }
}

export function setLang(lang) {
  try {
    const prefs = JSON.parse(localStorage.getItem(PREFS_KEY) || "{}");
    prefs.lang = lang;
    localStorage.setItem(PREFS_KEY, JSON.stringify(prefs));
  } catch {
    /* noop */
  }
  document.documentElement.lang = lang === "zh-CN" ? "zh-CN" : "en";
  window.dispatchEvent(new CustomEvent("quotax:lang-change", { detail: { lang } }));
}

/* key 是否在当前语言或中文兜底表里存在翻译。用于需要在缺失翻译时走别的
   fallback（如后端返回的原始 label）的场景——不能直接用 `t(key) || x`，
   因为 t() 在缺失时会返回 key 本身（非空字符串），|| 永远不会触发。 */
export function thas(key) {
  const dict = TRANSLATIONS[getLang()] || TRANSLATIONS["zh-CN"];
  return key in dict || key in TRANSLATIONS["zh-CN"];
}

export function t(key, vars = {}) {
  const dict = TRANSLATIONS[getLang()] || TRANSLATIONS["zh-CN"];
  const template = dict[key] ?? TRANSLATIONS["zh-CN"][key] ?? key;
  let s = String(template);
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{{${k}}}`, v);
  }
  return s;
}

export function toggleLang() {
  setLang(getLang() === "zh-CN" ? "en" : "zh-CN");
}
